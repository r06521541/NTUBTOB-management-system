def migration():
    spec = importlib.util.spec_from_file_location("erasure_work_items", MIGRATION)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class ErasureItemSchemaTests(unittest.TestCase):
    def sql(self):
        module = migration()
        with patch.object(module.op, "execute") as execute:
            module.upgrade()
        return "\n".join(str(call.args[0]) for call in execute.call_args_list)

    def test_exact_minimal_columns_and_no_private_payload(self):
        items = AccountErasureItemRecord.__table__
        events = AccountErasureItemEventRecord.__table__
        self.assertEqual(items.name, "account_erasure_items")
        self.assertEqual(events.name, "account_erasure_item_events")
        self.assertEqual(
            set(items.c.keys()),
            {
                "id",
                "job_id",
                "stage",
                "binding_hash",
                "expected_generation",
                "created_at",
            },
        )
        self.assertEqual(
            set(events.c.keys()),
            {
                "id",
                "item_id",
                "event_sequence",
                "event_kind",
                "result_code",
                "occurred_at",
            },
        )
        for table in (items, events):
            self.assertEqual(table.schema, "ntubtob")
            self.assertTrue(all(not column.nullable for column in table.c))
            self.assertEqual(len(table.foreign_keys), 1)
            self.assertEqual(next(iter(table.foreign_keys)).ondelete, "RESTRICT")
            for column in table.c:
                self.assertIsNone(column.default)
                if column.name not in {"id"}:
                    self.assertIsNone(column.server_default)
        self.assertTrue(items.c.created_at.type.timezone)
        self.assertTrue(events.c.occurred_at.type.timezone)
        self.assertIsNotNone(events.c.id.identity)
        self.assertIsNone(items.c.id.server_default)

    def test_postgresql_metadata_compiles_with_exact_restrict_targets(self):
        for model, target in (
            (AccountErasureItemRecord, "account_erasure_jobs"),
            (AccountErasureItemEventRecord, "account_erasure_items"),
        ):
            ddl = str(
                CreateTable(model.__table__).compile(dialect=postgresql.dialect())
            )
            self.assertIn(f"REFERENCES ntubtob.{target} (id) ON DELETE RESTRICT", ddl)
            self.assertNotIn("JSON", ddl)
            self.assertNotIn("CASCADE", ddl)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", ddl)

    def test_model_checks_and_uniqueness_match_incremental_ddl(self):
        self.assertEqual(migration().revision, "0017_erasure_work_items")
        self.assertEqual(migration().down_revision, "0016_erasure_cancellation")
        sql = " ".join(self.sql().split())
        expected = (
            (AccountErasureItemRecord, ("job_id", "stage", "binding_hash")),
            (AccountErasureItemEventRecord, ("item_id", "event_sequence")),
        )
        for model, unique_columns in expected:
            table = model.__table__
            self.assertIn(f"CREATE TABLE ntubtob.{table.name}", sql)
            uniques = []
            for constraint in table.constraints:
                if isinstance(constraint, CheckConstraint):
                    self.assertIn(constraint.name, sql)
                    self.assertIn(" ".join(str(constraint.sqltext).split()), sql)
                if isinstance(constraint, UniqueConstraint):
                    uniques.append(tuple(constraint.columns.keys()))
                    self.assertIn(constraint.name, sql)
            self.assertIn(unique_columns, uniques)

    def test_fixed_stages_results_and_finite_timestamps(self):
        sql = self.sql()
        for value in (
            "provider_revocation",
            "online_erasure",
            "manual_redaction",
            "restore_suppression",
            "in_progress",
            "succeeded",
            "credential_missing",
            "manual_action_needed",
            "not_applicable",
            "response_unknown",
            "scope_conflict",
            "dependency_unavailable",
            "verification_failed",
        ):
            self.assertIn(f"'{value}'", sql)
        self.assertIn("isfinite(created_at)", sql)
        self.assertIn("isfinite(occurred_at)", sql)
        self.assertIn("event_sequence > 0 AND event_sequence <= 3", sql)

    def test_item_insert_is_bound_to_locked_verified_job(self):
        sql = self.sql().split("CREATE FUNCTION ntubtob.guard_erasure_item()", 1)[1]
        sql = sql.split("CREATE FUNCTION ntubtob.guard_erasure_item_event()", 1)[0]
        self.assertIn(
            "FROM ntubtob.account_erasure_jobs WHERE id=NEW.job_id FOR UPDATE", sql
        )
        self.assertIn(
            "target_status NOT IN ('verified', 'processing', 'needs_attention')", sql
        )
        self.assertIn("NEW.expected_generation IS DISTINCT FROM target_generation", sql)
        self.assertIn("NEW.created_at < target_updated", sql)

    def test_event_guard_locks_job_before_item_and_reads_complete_history(self):
        sql = self.sql().split("CREATE FUNCTION ntubtob.guard_erasure_item_event()", 1)[
            1
        ]
        job_lock = sql.index(
            "FROM ntubtob.account_erasure_jobs WHERE id=target_job FOR UPDATE"
        )
        item_lock = sql.index(
            "FROM ntubtob.account_erasure_items WHERE id=NEW.item_id FOR UPDATE"
        )
        history = sql.index("FROM ntubtob.account_erasure_item_events")
        self.assertLess(job_lock, item_lock)
        self.assertLess(item_lock, history)
        for table in (
            "account_erasure_jobs",
            "account_erasure_items",
            "account_erasure_item_events",
        ):
            rls = sql.index(f"row_security_active('ntubtob.{table}'::regclass)")
            self.assertLess(rls, job_lock)
        self.assertIn("target_status <> 'processing'", sql)
        self.assertIn("target_fence IS NULL", sql)
        self.assertIn("NEW.occurred_at < target_fence", sql)
        self.assertIn("NEW.occurred_at < item_created", sql)
        self.assertIn("NEW.occurred_at < previous_time", sql)
        self.assertIn("previous_kind = 'unknown'", sql)
        self.assertIn("NEW.event_sequence = 3", sql)
        self.assertIn("NEW.event_kind IN ('confirmed', 'failed')", sql)

    def test_guards_require_read_committed_and_immutable_evidence(self):
        sql = self.sql()
        self.assertEqual(sql.count("current_setting('transaction_isolation')"), 2)
        self.assertEqual(sql.count("<> 'read committed'"), 2)
        for table, trigger in (
            ("account_erasure_items", "erasure_item_immutable"),
            ("account_erasure_item_events", "erasure_item_event_append_only"),
        ):
            self.assertIn(f"ALTER TABLE ntubtob.{table} ENABLE ROW LEVEL SECURITY", sql)
            self.assertIn(f"CREATE TRIGGER {trigger}", sql)
            self.assertIn(
                f"BEFORE UPDATE OR DELETE OR TRUNCATE ON ntubtob.{table}", sql
            )
        self.assertEqual(sql.count("ntubtob.reject_erasure_evidence_mutation()"), 2)

    def test_no_grants_defaults_backfill_or_destructive_downgrade(self):
        sql = self.sql()
        self.assertNotRegex(
            sql.upper().replace(
                "BEFORE UPDATE OR DELETE OR TRUNCATE ON", "BEFORE MUTATION ON"
            ),
            r"\b(GRANT|CREATE POLICY|DELETE FROM|TRUNCATE|DROP TABLE|SECURITY DEFINER)\b",
        )
        self.assertNotIn("DISABLE ROW LEVEL SECURITY", sql.upper())
        self.assertNotIn("ALTER TABLE ntubtob.account_erasure_jobs", sql)
        self.assertNotRegex(sql, r"INTERVAL|interval|30 days|90 days")
        module = migration()
        with patch.object(module.op, "execute") as execute:
            module.downgrade()
        execute.assert_not_called()


@unittest.skipUnless(
    fixture.DATABASE_URL, "dedicated isolated erasure URL not configured"
)
class ErasureItemPostgresTests(unittest.TestCase):
    setUpClass = classmethod(
        fixture.ErasureCancellationPostgresTests.setUpClass.__func__
    )
    tearDownClass = classmethod(
        fixture.ErasureCancellationPostgresTests.tearDownClass.__func__
    )
    job = fixture.ErasureCancellationPostgresTests.job
    update = fixture.ErasureCancellationPostgresTests.update
    rejected = fixture.ErasureCancellationPostgresTests.rejected

    def setUp(self):
        self.connection = self.engine.connect()
        self.addCleanup(self.connection.close)
        self.transaction = self.connection.begin()
        self.addCleanup(self.transaction.rollback)
        config = Config(str(ROOT / "alembic.ini"))
        config.attributes["connection"] = self.connection
        command.upgrade(config, "0017_erasure_work_items")
        self.person = self.connection.scalar(
            text(
                "INSERT INTO ntubtob.people (display_name,portal_access_level,portal_status,version,created_at,updated_at) VALUES ('Fictional item person','basic','active',1,:now,:now) RETURNING id"
            ),
            {"now": fixture.NOW},
        )

    def item(self, job_id, **changes):
        values = dict(
            id=str(uuid4()),
            job_id=job_id,
            stage="provider_revocation",
            binding_hash="a" * 64,
            expected_generation=self.generation,
            created_at=CREATED,
        )
        values.update(changes)
        self.connection.execute(
            text(
                "INSERT INTO ntubtob.account_erasure_items (id,job_id,stage,binding_hash,expected_generation,created_at) VALUES (:id,:job_id,:stage,:binding_hash,:expected_generation,:created_at)"
            ),
            values,
        )
        return values["id"]

    def event(self, item_id, **changes):
        values = dict(
            item_id=item_id,
            event_sequence=1,
            event_kind="started",
            result_code="in_progress",
            occurred_at=STARTED,
        )
        values.update(changes)
        self.connection.execute(
            text(
                "INSERT INTO ntubtob.account_erasure_item_events (item_id,event_sequence,event_kind,result_code,occurred_at) VALUES (:item_id,:event_sequence,:event_kind,:result_code,:occurred_at)"
            ),
            values,
        )

    def verified(self):
        self.generation = str(uuid4())
        job = self.job(expected_generation=self.generation)
        self.update(job, status="verified", verified_at=CREATED, updated_at=CREATED)
        return job

    def start(self, job):
        self.update(
            job,
            status="processing",
            irreversible_started_at=STARTED,
            updated_at=STARTED,
        )

    def test_item_scope_status_uniqueness_and_immutability(self):
        self.generation = str(uuid4())
        job = self.job(expected_generation=self.generation)
        self.rejected(lambda: self.item(job))
        self.update(job, status="verified", verified_at=CREATED, updated_at=CREATED)
        item = self.item(job)
        self.rejected(lambda: self.item(job))
        for changes in (
            {"expected_generation": str(uuid4())},
            {"stage": "unknown"},
            {"binding_hash": "private subject"},
            {"created_at": fixture.NOW},
            {"created_at": "infinity"},
        ):
            with self.subTest(fields=tuple(changes)):
                # Do not let the existing unique binding mask the intended guard.
                self.rejected(
                    lambda: self.item(job, **({"binding_hash": "b" * 64} | changes))
                )
        for sql in (
            "UPDATE ntubtob.account_erasure_items SET binding_hash=repeat('b',64)",
            "DELETE FROM ntubtob.account_erasure_items",
            "TRUNCATE ntubtob.account_erasure_items",
        ):
            self.rejected(lambda: self.connection.execute(text(sql)))
        self.assertEqual(
            str(
                self.connection.scalar(
                    text("SELECT id FROM ntubtob.account_erasure_items")
                )
            ),
            item,
        )

    def test_start_requires_processing_and_fence_and_current_time(self):
        job = self.verified()
        item = self.item(job)
        self.rejected(lambda: self.event(item))
        self.update(job, status="processing")
        self.rejected(lambda: self.event(item))
        self.start(job)
        for changes in (
            {"event_sequence": 2},
            {"occurred_at": CREATED},
            {"occurred_at": "infinity"},
            {"event_kind": "confirmed", "result_code": "succeeded"},
        ):
            self.rejected(lambda: self.event(item, **changes))
        self.event(item)
        self.rejected(lambda: self.event(item))

    def test_unknown_only_allows_one_explicit_reconciliation(self):
        job = self.verified()
        item = self.item(job)
        self.start(job)
        self.event(item)
        self.event(
            item,
            event_sequence=2,
            event_kind="unknown",
            result_code="response_unknown",
            occurred_at=FINISHED,
        )
        for changes in (
            {"event_sequence": 3},
            {
                "event_sequence": 3,
                "event_kind": "unknown",
                "result_code": "response_unknown",
            },
            {
                "event_sequence": 4,
                "event_kind": "confirmed",
                "result_code": "succeeded",
            },
            {
                "event_sequence": 3,
                "event_kind": "confirmed",
                "result_code": "succeeded",
                "occurred_at": STARTED,
            },
        ):
            self.rejected(lambda: self.event(item, **changes))
        self.update(job, status="needs_attention", updated_at=FINISHED)
        self.event(
            item,
            event_sequence=3,
            event_kind="confirmed",
            result_code="credential_missing",
            occurred_at=FINISHED,
        )
        self.rejected(
            lambda: self.event(
                item,
                event_sequence=3,
                event_kind="failed",
                result_code="scope_conflict",
                occurred_at=FINISHED,
            )
        )
        self.assertEqual(
            self.connection.scalar(
                text("SELECT count(*) FROM ntubtob.account_erasure_item_events")
            ),
            3,
        )

    def test_completed_item_cannot_restart_and_events_are_immutable(self):
        job = self.verified()
        item = self.item(job)
        self.start(job)
        self.event(item)
        self.event(
            item,
            event_sequence=2,
            event_kind="confirmed",
            result_code="succeeded",
            occurred_at=FINISHED,
        )
        self.rejected(
            lambda: self.event(
                item,
                event_sequence=3,
                event_kind="failed",
                result_code="scope_conflict",
                occurred_at=FINISHED,
            )
        )
        for sql in (
            "UPDATE ntubtob.account_erasure_item_events SET result_code='not_applicable'",
            "DELETE FROM ntubtob.account_erasure_item_events",
            "TRUNCATE ntubtob.account_erasure_item_events",
        ):
            self.rejected(lambda: self.connection.execute(text(sql)))
        config = Config(str(ROOT / "alembic.ini"))
        config.attributes["connection"] = self.connection
        command.downgrade(config, "0016_erasure_cancellation")
        self.assertEqual(
            self.connection.scalar(
                text("SELECT count(*) FROM ntubtob.account_erasure_item_events")
            ),
            2,
        )
        self.rejected(
            lambda: self.connection.execute(
                text("DELETE FROM ntubtob.account_erasure_item_events")
            )
        )

    def test_fixed_result_matrix_and_failed_item_cannot_retry(self):
        job = self.verified()
        results = (
            ("confirmed", "succeeded"),
            ("confirmed", "credential_missing"),
            ("confirmed", "manual_action_needed"),
            ("confirmed", "not_applicable"),
            ("failed", "scope_conflict"),
            ("failed", "dependency_unavailable"),
            ("failed", "verification_failed"),
        )
        items = [
            self.item(job, binding_hash=f"{index:064x}")
            for index in range(len(results))
        ]
        self.start(job)
        for item, (kind, code) in zip(items, results):
            with self.subTest(kind=kind, code=code):
                self.event(item)
                self.rejected(
                    lambda: self.event(
                        item,
                        event_sequence=2,
                        event_kind=kind,
                        result_code="private-exception",
                        occurred_at=FINISHED,
                    )
                )
                self.event(
                    item,
                    event_sequence=2,
                    event_kind=kind,
                    result_code=code,
                    occurred_at=FINISHED,
                )
                self.rejected(
                    lambda: self.event(
                        item,
                        event_sequence=3,
                        event_kind="confirmed",
                        result_code="succeeded",
                        occurred_at=FINISHED,
                    )
                )
        self.assertEqual(
            self.connection.scalar(
                text("SELECT count(*) FROM ntubtob.account_erasure_item_events")
            ),
            2 * len(results),
        )

    def test_cancelled_target_cannot_acquire_items_and_retaining_downgrade_keeps_evidence(
        self,
    ):
        job = self.verified()
        item = self.item(job)
        self.update(
            job,
            status="cancelled",
            person_id=None,
            cancelled_at=STARTED,
            updated_at=STARTED,
        )
        self.rejected(lambda: self.item(job, binding_hash="b" * 64, created_at=STARTED))
        self.rejected(lambda: self.event(item))
        config = Config(str(ROOT / "alembic.ini"))
        config.attributes["connection"] = self.connection
        command.downgrade(config, "0016_erasure_cancellation")
        self.assertEqual(
            str(
                self.connection.scalar(
                    text("SELECT id FROM ntubtob.account_erasure_items")
                )
            ),
            item,
        )
        self.rejected(
            lambda: self.connection.execute(
                text("DELETE FROM ntubtob.account_erasure_items")
            )
        )


